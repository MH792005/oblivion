/// Derive a hardware-bound cryptographic key using static salt and hardware attributes.
/// Returns a 32-byte heap-allocated key pointer. The caller must free it via `oblivion_free_key`.
#[no_mangle]
pub unsafe extern "C" fn derive_hardware_key(salt: *const u8, salt_len: usize) -> *mut u8 {
    if salt.is_null() || salt_len == 0 {
        return std::ptr::null_mut();
    }

    let salt_slice = slice::from_raw_parts(salt, salt_len);
    
    // Create transient zeroized buffer
    let mut key_buffer = vec![0u8; 32];

    // Combine static salt with simulated hardware unique attributes & scrambled lookup tables
    for (i, byte) in key_buffer.iter_mut().enumerate() {
        let salt_byte = salt_slice[i % salt_slice.len()];
        let table_val = WHITEBOX_SBOX[(salt_byte as usize + i) % 256];
        let mix_val = (WHITEBOX_MIX_TABLE[i % 16] >> ((i % 4) * 8)) as u8;
        *byte = table_val ^ mix_val ^ (i as u8 * 0x37);
    }

    let ptr = key_buffer.as_mut_ptr();
    std::mem::forget(key_buffer); // Hand ownership to C caller
    ptr
}

/// White-box AES / custom block decryption routine.
/// Operates in-place on data slice. Guaranteed zero-memory residue for intermediate keys.
#[no_mangle]
pub unsafe extern "C" fn whitebox_decrypt(
    data: *mut u8,
    len: usize,
    key: *const u8,
    key_len: usize,
) -> i32 {
    if data.is_null() || len == 0 || key.is_null() || key_len == 0 {
        return -1;
    }

    let data_slice = slice::from_raw_parts_mut(data, len);
    let key_slice = slice::from_raw_parts(key, key_len);

    // Scratch space with zeroize auto-clearing on drop
    let mut round_keys = vec![0u8; 256];

    for i in 0..round_keys.len() {
        let k_byte = key_slice[i % key_slice.len()];
        let s_val = WHITEBOX_SBOX[k_byte as usize];
        round_keys[i] = s_val ^ (i as u8);
    }

    // Scrambled lookup table-based block mutation
    for (idx, byte) in data_slice.iter_mut().enumerate() {
        let rk = round_keys[idx % round_keys.len()];
        let sbox_out = WHITEBOX_SBOX[(*byte ^ rk) as usize];
        *byte = sbox_out ^ (WHITEBOX_MIX_TABLE[idx % 16] as u8);
    }

    // Explicitly zeroize scratch keys before exiting function frame
    round_keys.zeroize();

    0
}

/// Securely zeroize and free a hardware key buffer created by `derive_hardware_key`.
#[no_mangle]
pub unsafe extern "C" fn oblivion_free_key(ptr: *mut u8, len: usize) {
    if ptr.is_null() || len == 0 {
        return;
    }
    let mut vec_buffer = Vec::from_raw_parts(ptr, len, len);
    vec_buffer.zeroize();
    // Memory automatically deallocated at end of scope after zeroize
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_key_derivation_and_zeroize() {
        unsafe {
            let salt = b"OBLIVION_STATIC_SALT_2026";
            let key_ptr = derive_hardware_key(salt.as_ptr(), salt.len());
            assert!(!key_ptr.is_null());

            let mut data = vec![1, 2, 3, 4, 5];
            let res = whitebox_decrypt(data.as_mut_ptr(), data.len(), key_ptr, 32);
            assert_eq!(res, 0);

            oblivion_free_key(key_ptr, 32);
        }
    }
}
